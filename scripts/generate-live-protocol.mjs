/**
 * Generates the live-update protocol module (zod validators plus inferred
 * types) from the AsyncAPI document that defines it.
 *
 *   node scripts/generate-live-protocol.mjs <asyncapi.yaml> <output.ts>
 *
 * `apps/api/asyncapi.yaml` is the protocol's source of truth; the API and the
 * web client each commit their generated copy, and CI regenerates both and
 * fails on any diff. Only the subset of AsyncAPI 3.0 and JSON Schema the
 * protocol uses is supported: local `#/` references, one `send` operation on
 * one channel, and message payloads that are objects discriminated by a
 * `type` constant. Anything else fails generation instead of degrading.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { jsonSchemaToZod } from "json-schema-to-zod";
import prettier from "prettier";
import { parse as parseYaml } from "yaml";

const SUPPORTED_SCHEMA_KEYWORDS = new Set([
  "type",
  "enum",
  "const",
  "format",
  "minimum",
  "description",
  "properties",
  "required",
  "additionalProperties",
  "$ref",
]);

/** Follows a local `#/a/b` pointer within the document. */
function resolvePointer(document, ref) {
  if (!ref.startsWith("#/")) {
    throw new Error(`Only local references are supported: ${ref}`);
  }
  let node = document;
  for (const segment of ref.slice(2).split("/")) {
    node = node?.[segment.replaceAll("~1", "/").replaceAll("~0", "~")];
    if (node === undefined) throw new Error(`Unresolved reference: ${ref}`);
  }
  return node;
}

/** Returns `schema` with every `$ref` inlined, rejecting unsupported keywords. */
export function inlineSchema(document, schema, seen = []) {
  if (typeof schema !== "object" || schema === null) return schema;
  for (const key of Object.keys(schema)) {
    if (!SUPPORTED_SCHEMA_KEYWORDS.has(key)) {
      throw new Error(`Unsupported JSON Schema keyword: ${key}`);
    }
  }
  if (schema.$ref) {
    if (seen.includes(schema.$ref)) {
      throw new Error(`Recursive reference: ${schema.$ref}`);
    }
    return inlineSchema(document, resolvePointer(document, schema.$ref), [
      ...seen,
      schema.$ref,
    ]);
  }
  if (!schema.properties) return { ...schema };
  return {
    ...schema,
    properties: Object.fromEntries(
      Object.entries(schema.properties).map(([name, property]) => [
        name,
        inlineSchema(document, property, seen),
      ]),
    ),
  };
}

function pascalCase(name) {
  return name.charAt(0).toUpperCase() + name.slice(1);
}

function camelCase(name) {
  return name.charAt(0).toLowerCase() + name.slice(1);
}

/** The single `send` operation's channel and its messages, resolved. */
function sendOperation(document) {
  const operations = Object.values(document.operations ?? {}).filter(
    (operation) => operation.action === "send",
  );
  if (operations.length !== 1) {
    throw new Error(
      `Expected exactly one send operation, found ${operations.length}`,
    );
  }
  const [operation] = operations;
  const channel = resolvePointer(document, operation.channel.$ref);
  const messages = operation.messages.map((reference) => {
    const message = resolvePointer(document, reference.$ref);
    const resolved = message.$ref
      ? resolvePointer(document, message.$ref)
      : message;
    const payloadRef = resolved.payload?.$ref;
    if (!payloadRef?.startsWith("#/components/schemas/")) {
      throw new Error(
        `Message ${resolved.name} needs a component schema payload`,
      );
    }
    return { name: resolved.name, schemaName: payloadRef.split("/").at(-1) };
  });
  return { address: channel.address, messages };
}

/** Checks that a payload is an object discriminated by a `type` constant. */
function assertDiscriminated(document, message) {
  const schema = inlineSchema(
    document,
    document.components.schemas[message.schemaName],
  );
  const discriminator = schema.properties?.type?.const;
  if (schema.type !== "object" || discriminator !== message.name) {
    throw new Error(
      `${message.schemaName} must be an object whose type const is "${message.name}"`,
    );
  }
}

/**
 * Renders the generated TypeScript module for a parsed AsyncAPI document,
 * formatted with the Prettier configuration that applies to `outputPath`, so
 * each copy matches its workspace's style.
 */
export async function renderLiveProtocol(document, sourceLabel, outputPath) {
  if (document.asyncapi !== "3.0.0") {
    throw new Error(`Expected AsyncAPI 3.0.0, found ${document.asyncapi}`);
  }
  const { address, messages } = sendOperation(document);
  for (const message of messages) assertDiscriminated(document, message);

  const lines = [
    `// Generated by scripts/generate-live-protocol.mjs from ${sourceLabel}.`,
    "// Do not edit: change the AsyncAPI document and regenerate.",
    'import { z } from "zod";',
    "",
    `export const LIVE_CHANNEL_ADDRESS = ${JSON.stringify(address)};`,
  ];
  for (const [name, schema] of Object.entries(document.components.schemas)) {
    const zod = jsonSchemaToZod(inlineSchema(document, schema), {
      module: "none",
    });
    if (schema.description) lines.push("", `/** ${schema.description} */`);
    else lines.push("");
    lines.push(`export const ${camelCase(name)}Schema = ${zod};`);
    lines.push(
      `export type ${pascalCase(name)} = z.infer<typeof ${camelCase(name)}Schema>;`,
    );
  }
  const members = messages.map((m) => `${camelCase(m.schemaName)}Schema`);
  lines.push(
    "",
    "/** Every message the server sends on the channel. */",
    `export const liveMessageSchema = z.discriminatedUnion("type", [${members.join(", ")}]);`,
    "export type LiveMessage = z.infer<typeof liveMessageSchema>;",
    "",
  );
  const options = outputPath ? await prettier.resolveConfig(outputPath) : null;
  return prettier.format(lines.join("\n"), {
    ...options,
    parser: "typescript",
  });
}

async function main([input, output]) {
  if (!input || !output) {
    throw new Error(
      "usage: generate-live-protocol.mjs <asyncapi.yaml> <output.ts>",
    );
  }
  const document = parseYaml(readFileSync(input, "utf8"));
  const repositoryRoot = path.resolve(import.meta.dirname, "..");
  const label = path
    .relative(repositoryRoot, path.resolve(input))
    .replaceAll(path.sep, "/");
  const source = await renderLiveProtocol(
    document,
    label,
    path.resolve(output),
  );
  mkdirSync(path.dirname(output), { recursive: true });
  writeFileSync(output, source);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  main(process.argv.slice(2)).catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
